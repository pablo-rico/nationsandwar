ORDER = ["overview", "town", "roles", "provinces", "nation", "nation_roles", "diplomacy", "war", "map", "crown", "scroll"]

def main():
    rows = [[PAL["."]] * 256 for _ in range(16)]
    for i, name in enumerate(ORDER):
        art = ICONS[name]
        assert len(art) == 16, name
        for y, line in enumerate(art):
            line = (line + "." * 16)[:16]
            for x, ch in enumerate(line):
                rows[y][i * 16 + x] = PAL[ch]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    write_png(OUT, rows)
    print("wrote", OUT)

if __name__ == "__main__":
    main()
